BotGpt::BotGpt(std::shared_ptr<GameSession::IGamePlayerAction> action_interface,
                             const PlayerType player_type)
    : PlayerBotBase(action_interface, player_type),
      gen_(rd_()) {
    enemy_.assign(Board::kBoardSizeRow,
                  std::vector<Cell>(Board::kBoardSizeCol, Cell::Unknown));
    LOG_I("Create a bot generated by ChatGpt");
    initRemainingShipsFromBoardRules();
}

void BotGpt::initRemainingShipsFromBoardRules() {
    remaining_lengths_.clear();
    for (int t = 0; t < static_cast<int>(Board::ShipType::NumberOfShips); ++t) {
        auto type = static_cast<Board::ShipType>(t);
        const size_t count = Board::get_max_ship_count(type);
        const int len = static_cast<int>(Board::get_ship_size(type));
        for (size_t i = 0; i < count; ++i) remaining_lengths_.push_back(len);
    }
    // optional: keep sorted (helps debugging)
    std::sort(remaining_lengths_.begin(), remaining_lengths_.end());
}

