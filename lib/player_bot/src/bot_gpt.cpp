bool BotGpt::isValidTarget(const Board::Position& pos) const {
    const int r = pos.first, c = pos.second;
    if (r < 0 || c < 0) return false;
    if (r >= static_cast<int>(Board::kBoardSizeRow) ||
        c >= static_cast<int>(Board::kBoardSizeCol))
        return false;

    if (enemy_[r][c] != Cell::Unknown) return false;
    return Board::Board::is_valid_shot(oponent_board_, pos);
}

Board::Position BotGpt::randomPosition() {
    std::uniform_int_distribution<> row(0, Board::kBoardSizeRow - 1);
    std::uniform_int_distribution<> col(0, Board::kBoardSizeCol - 1);
    return {row(gen_), col(gen_)};
}

std::vector<std::vector<bool>> BotGpt::visitedMask() const {
    return std::vector<std::vector<bool>>(Board::kBoardSizeRow,
                                          std::vector<bool>(Board::kBoardSizeCol, false));
}

std::vector<Board::Position> BotGpt::collectHitClusterFrom(const Board::Position& start) const {
    std::vector<Board::Position> cluster;
    if (start.first < 0) return cluster;

    auto vis = visitedMask();
    std::queue<Board::Position> q;

    auto pushIfHit = [&](int r, int c) {
        if (r < 0 || c < 0) return;
        if (r >= static_cast<int>(Board::kBoardSizeRow) ||
            c >= static_cast<int>(Board::kBoardSizeCol))
            return;
        if (vis[r][c]) return;
        if (enemy_[r][c] != Cell::Hit) return;
        vis[r][c] = true;
        q.push({r, c});
    };

    pushIfHit(start.first, start.second);
    while (!q.empty()) {
        auto p = q.front(); q.pop();
        cluster.push_back(p);

        pushIfHit(p.first - 1, p.second);
        pushIfHit(p.first + 1, p.second);
        pushIfHit(p.first, p.second - 1);
        pushIfHit(p.first, p.second + 1);
    }

    return cluster;
}

std::vector<std::vector<Board::Position>> BotGpt::getAllHitClusters() const {
    auto vis = visitedMask();
    std::vector<std::vector<Board::Position>> clusters;

    for (int r = 0; r < static_cast<int>(Board::kBoardSizeRow); ++r) {
        for (int c = 0; c < static_cast<int>(Board::kBoardSizeCol); ++c) {
            if (vis[r][c]) continue;
            if (enemy_[r][c] != Cell::Hit) continue;

            // BFS
            std::vector<Board::Position> cluster;
            std::queue<Board::Position> q;
            vis[r][c] = true;
            q.push({r, c});

            while (!q.empty()) {
                auto p = q.front(); q.pop();
                cluster.push_back(p);

                const int dr[4] = {-1, 1, 0, 0};
                const int dc[4] = {0, 0, -1, 1};
                for (int i = 0; i < 4; ++i) {
                    int rr = p.first + dr[i], cc = p.second + dc[i];
                    if (rr < 0 || cc < 0) continue;
                    if (rr >= static_cast<int>(Board::kBoardSizeRow) ||
                        cc >= static_cast<int>(Board::kBoardSizeCol))
                        continue;
                    if (vis[rr][cc]) continue;
                    if (enemy_[rr][cc] != Cell::Hit) continue;
                    vis[rr][cc] = true;
                    q.push({rr, cc});
                }
            }

            clusters.push_back(std::move(cluster));
        }
    }
    return clusters;
}

std::vector<Board::Position> BotGpt::chooseTargetCluster() const {
    auto clusters = getAllHitClusters();
    if (clusters.empty()) return {};

    // Choose the largest cluster (most likely to be close to sinking)
    auto it = std::max_element(clusters.begin(), clusters.end(),
                              [](auto& a, auto& b) { return a.size() < b.size(); });
    return *it;
}

bool BotGpt::placementConsistent(int r, int c, bool horizontal, int L,
                                        const std::vector<Board::Position>& targetCluster) const {
    // Placement cells cannot include Miss/Sunk
    // Also: if we are targeting a cluster, placement must include all its cells
    // and must not include Hit cells outside that cluster.
    auto inPlacement = [&](int rr, int cc) {
        if (horizontal) return (rr == r && cc >= c && cc < c + L);
        return (cc == c && rr >= r && rr < r + L);
    };

    // quick bounds are ensured by loops in heatmap creation

    for (int k = 0; k < L; ++k) {
        int rr = r + (horizontal ? 0 : k);
        int cc = c + (horizontal ? k : 0);

        Cell cell = enemy_[rr][cc];
        if (cell == Cell::Miss || cell == Cell::Sunk) return false;
    }

    if (!targetCluster.empty()) {
        // must include all cells from target cluster
        for (const auto& h : targetCluster) {
            if (!inPlacement(h.first, h.second)) return false;
        }

        // must NOT include any other hits outside the cluster
        // (prevents combining two separate hit clusters into one impossible ship)
        for (int rr = 0; rr < static_cast<int>(Board::kBoardSizeRow); ++rr) {
            for (int cc = 0; cc < static_cast<int>(Board::kBoardSizeCol); ++cc) {
                if (enemy_[rr][cc] != Cell::Hit) continue;
                bool isInTarget = std::find(targetCluster.begin(), targetCluster.end(),
                                            Board::Position{rr, cc}) != targetCluster.end();
                if (!isInTarget && inPlacement(rr, cc)) return false;
            }
        }
    }

    return true;
}

Board::Position BotGpt::bestHeatmapShot() {
    const int R = static_cast<int>(Board::kBoardSizeRow);
    const int C = static_cast<int>(Board::kBoardSizeCol);

    std::vector<std::vector<int>> heat(R, std::vector<int>(C, 0));

    const auto targetCluster = chooseTargetCluster();

    // If we have hits, ignore pure-hunt placements (no-hit placements)
    // by only counting placements consistent with the cluster constraint.

    for (int L : remaining_lengths_) {
        // horizontal
        for (int r = 0; r < R; ++r) {
            for (int c = 0; c + L - 1 < C; ++c) {
                if (!placementConsistent(r, c, true, L, targetCluster)) continue;

                // If targeting, ensure placement actually covers the cluster
                // (already guaranteed when targetCluster non-empty)
                for (int k = 0; k < L; ++k) {
                    if (enemy_[r][c + k] == Cell::Unknown)
                        heat[r][c + k] += 1;
                }
            }
        }
        // vertical
        for (int r = 0; r + L - 1 < R; ++r) {
            for (int c = 0; c < C; ++c) {
                if (!placementConsistent(r, c, false, L, targetCluster)) continue;

                for (int k = 0; k < L; ++k) {
                    if (enemy_[r + k][c] == Cell::Unknown)
                        heat[r + k][c] += 1;
                }
            }
        }
    }

    int best = -1;
    std::vector<Board::Position> bestCells;

    for (int r = 0; r < R; ++r) {
        for (int c = 0; c < C; ++c) {
            Board::Position p{r, c};
            if (!isValidTarget(p)) continue;
            if (heat[r][c] > best) {
                best = heat[r][c];
                bestCells.clear();
                bestCells.push_back(p);
            } else if (heat[r][c] == best) {
                bestCells.push_back(p);
            }
        }
    }

    if (bestCells.empty()) {
        if (auto any = findAnyValidTarget(); any.has_value())
            return *any;

        LOG_E("BotGpt: No valid targets left, but game not finished. "
            "enemy_ Unknown cells: {}", 
            std::count_if(enemy_.begin(), enemy_.end(), [](auto& row){
                return std::count(row.begin(), row.end(), Cell::Unknown);
            }));
        throw std::runtime_error("BotGpt: no valid shots left");
    }

    std::uniform_int_distribution<> pick(0, static_cast<int>(bestCells.size()) - 1);
    return bestCells[pick(gen_)];
}

RequestId BotGpt::makeShot() {
    Board::Position pos = bestHeatmapShot();
    if (!isValidTarget(pos)) {
        LOG_E("BotGpt produced invalid shot ({}, {})", pos.first, pos.second);
        throw std::runtime_error("BotGpt invalid shot");
    }
    return action_interface_->makeShot(pos);
}

