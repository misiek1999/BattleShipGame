int BotGpt::edgeDist(int r, int c) {
    const int top = r;
    const int left = c;
    const int bottom = static_cast<int>(Board::kBoardSizeRow) - 1 - r;
    const int right  = static_cast<int>(Board::kBoardSizeCol) - 1 - c;
    return std::min({top, left, bottom, right}); // 0 at edge
}

int BotGpt::shipPlacementScore(Board::Position pos, bool horizontal, size_t L) const {
    // Lower score = preferred
    int score = 0;

    for (size_t k = 0; k < L; ++k) {
        int r = pos.first  + (horizontal ? 0 : static_cast<int>(k));
        int c = pos.second + (horizontal ? static_cast<int>(k) : 0);

        score += 2 * edgeDist(r, c); // prefer edges/corners

        // Small “spread” penalty: avoid being close to existing ships
        // (even if your placement rules already prevent adjacency, this still helps spacing)
        for (int dr = -2; dr <= 2; ++dr) {
            for (int dc = -2; dc <= 2; ++dc) {
                int rr = r + dr, cc = c + dc;
                if (rr < 0 || cc < 0) continue;
                if (rr >= static_cast<int>(Board::kBoardSizeRow) ||
                    cc >= static_cast<int>(Board::kBoardSizeCol)) continue;

                if (board_[rr][cc].field == Board::BoardFieldStatus::Ship) {
                    score += 3;
                }
            }
        }
    }
    return score;
}

RequestId BotGpt::placeShip(const Board::ShipType ship_type) {
    // Detect start of a new game:
    // - engine cleared our local board_ (no ships)
    // - but we previously placed ships in an earlier game
    const bool board_empty_now = !ownBoardHasAnyShips();
    if (!new_game_initialized_ || (ships_placed_in_current_game_ > 0 && board_empty_now)) {
        resetForNewGame();
    }

    std::uniform_int_distribution<> row(0, Board::kBoardSizeRow - 1);
    std::uniform_int_distribution<> col(0, Board::kBoardSizeCol - 1);
    std::uniform_int_distribution<> rot(0, 1);

    const size_t L = Board::get_ship_size(ship_type);

    constexpr int kTries = 500;
    bool found = false;
    int bestScore = std::numeric_limits<int>::max();
    Board::Position bestPos{0, 0};
    bool bestHorizontal = true;

    for (int t = 0; t < kTries; ++t) {
        Board::Position pos{row(gen_), col(gen_)};
        bool horizontal = (rot(gen_) != 0);

        const bool is_vertical = !horizontal;
        if (!Board::Board::is_possible_to_place_ship(board_, pos, ship_type, is_vertical))
            continue;

        int score = shipPlacementScore(pos, horizontal, L);
        if (score < bestScore) {
            bestScore = score;
            bestPos = pos;
            bestHorizontal = horizontal;
            found = true;
        }
    }

    if (!found) {
        // fallback: original random loop
        Board::Position pos;
        bool horizontal;
        do {
            pos = {row(gen_), col(gen_)};
            horizontal = (rot(gen_) != 0);
        } while (!Board::Board::is_possible_to_place_ship(board_, pos, ship_type, !horizontal));
        return action_interface_->placeShip(ship_type, pos, horizontal);
    }
    ++ships_placed_in_current_game_;

    return action_interface_->placeShip(ship_type, bestPos, bestHorizontal);
}

