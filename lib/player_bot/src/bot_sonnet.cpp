RequestId BotSonnet::makeShot() {
    Board::Position pos;

    if (mode_ == Mode::Target && !target_queue_.empty()) {
        // In target mode: prioritize based on hit chain orientation
        prioritizeTargetQueue();

        pos = target_queue_.front();
        target_queue_.pop_front();

        // Ensure target is still valid
        while (!isValidTarget(pos) && !target_queue_.empty()) {
            pos = target_queue_.front();
            target_queue_.pop_front();
        }

        if (!isValidTarget(pos)) {
            mode_ = Mode::Hunt;
            pos = findBestHuntTarget();
        }
    } else {
        // Hunt mode: use probability density
        mode_ = Mode::Hunt;
        pos = findBestHuntTarget();
    }

    tried_[pos.first][pos.second] = true;
    return action_interface_->makeShot(pos);
}

Board::Position BotSonnet::findBestHuntTarget() {
    auto prob_map = calculateProbabilityMap();

    // Find maximum probability
    double max_prob = -1.0;
    std::vector<Board::Position> best_positions;

    for (size_t r = 0; r < Board::kBoardSizeRow; ++r) {
        for (size_t c = 0; c < Board::kBoardSizeCol; ++c) {
            Board::Position pos{static_cast<int>(r), static_cast<int>(c)};

            if (!isValidTarget(pos)) continue;

            double prob = prob_map[r][c];

            if (prob > max_prob) {
                max_prob = prob;
                best_positions.clear();
                best_positions.push_back(pos);
            } else if (std::abs(prob - max_prob) < 0.001) {  // Essentially equal
                best_positions.push_back(pos);
            }
        }
    }

    // Fallback to random if no valid targets
    if (best_positions.empty()) {
        Board::Position pos;
        do {
            pos = randomPosition();
        } while (!isValidTarget(pos));
        return pos;
    }

    // Randomly select among best positions
    std::uniform_int_distribution<size_t> pick(0, best_positions.size() - 1);
    return best_positions[pick(gen_)];
}

std::vector<std::vector<double>> BotSonnet::calculateProbabilityMap() const {
    std::vector<std::vector<double>> prob_map(
        Board::kBoardSizeRow,
        std::vector<double>(Board::kBoardSizeCol, 0.0));

    // For each remaining ship, count how many valid placements cover each cell
    for (size_t ship_size : remaining_ship_sizes_) {
        if (ship_size == 0) continue;

        // Horizontal placements
        for (size_t r = 0; r < Board::kBoardSizeRow; ++r) {
            for (size_t c = 0; c <= Board::kBoardSizeCol - ship_size; ++c) {
                Board::Position start{static_cast<int>(r), static_cast<int>(c)};

                if (canShipFitAt(start, ship_size, false)) {  // horizontal
                    // This placement is valid - increment probability for covered cells
                    for (size_t i = 0; i < ship_size; ++i) {
                        prob_map[r][c + i] += 1.0;
                    }
                }
            }
        }

        // Vertical placements (only if ship_size > 1, otherwise already counted)
        if (ship_size > 1) {
            for (size_t r = 0; r <= Board::kBoardSizeRow - ship_size; ++r) {
                for (size_t c = 0; c < Board::kBoardSizeCol; ++c) {
                    Board::Position start{static_cast<int>(r), static_cast<int>(c)};

                    if (canShipFitAt(start, ship_size, true)) {  // vertical
                        for (size_t i = 0; i < ship_size; ++i) {
                            prob_map[r + i][c] += 1.0;
                        }
                    }
                }
            }
        }
    }

    // Apply parity optimization (only effective for ships size >= 2)
    size_t min_remaining_size = remaining_ship_sizes_.empty() ? 1 :
        *std::min_element(remaining_ship_sizes_.begin(), remaining_ship_sizes_.end());

    if (min_remaining_size >= 2) {
        // Use checkerboard pattern for efficiency
        for (size_t r = 0; r < Board::kBoardSizeRow; ++r) {
            for (size_t c = 0; c < Board::kBoardSizeCol; ++c) {
                // Checkerboard pattern: prioritize cells where (r+c) is even
                if ((r + c) % 2 == 0) {
                    prob_map[r][c] *= 1.1;  // 10% boost
                }
            }
        }
    }

    // Boost cells adjacent to isolated hits (increases chance of finding rest of ship)
    for (size_t r = 0; r < Board::kBoardSizeRow; ++r) {
        for (size_t c = 0; c < Board::kBoardSizeCol; ++c) {
            if (cell_states_[r][c] == CellState::Hit) {
                // Boost adjacent cells
                static const int dr[] = {-1, 1, 0, 0};
                static const int dc[] = {0, 0, -1, 1};

                for (int i = 0; i < 4; ++i) {
                    int nr = static_cast<int>(r) + dr[i];
                    int nc = static_cast<int>(c) + dc[i];

                    if (nr >= 0 && nr < static_cast<int>(Board::kBoardSizeRow) &&
                        nc >= 0 && nc < static_cast<int>(Board::kBoardSizeCol) &&
                        cell_states_[nr][nc] == CellState::Unknown) {
                        prob_map[nr][nc] *= 2.0;  // Strong boost for cells near hits
                    }
                }
            }
        }
    }

    return prob_map;
}

bool BotSonnet::canShipFitAt(const Board::Position& start,
                                  size_t size, bool is_vertical) const {
    for (size_t i = 0; i < size; ++i) {
        int r = is_vertical ? start.first + static_cast<int>(i) : start.first;
        int c = is_vertical ? start.second : start.second + static_cast<int>(i);

        // Check bounds
        if (r < 0 || c < 0 ||
            static_cast<size_t>(r) >= Board::kBoardSizeRow ||
            static_cast<size_t>(c) >= Board::kBoardSizeCol) {
            return false;
        }

        // Check if cell was a miss (can't place ship through a miss)
        if (cell_states_[r][c] == CellState::Miss) {
            return false;
        }

        // Note: Hits are okay - ship could extend through known hit cells
    }
    return true;
}

