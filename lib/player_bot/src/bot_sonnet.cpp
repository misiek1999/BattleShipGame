void BotSonnet::onPlayerShotResult(const Board::Position& position,
                                        const bool is_hit,
                                        const bool is_ship_sunk) {
    // Update cell state tracking
    cell_states_[position.first][position.second] =
        is_hit ? CellState::Hit : CellState::Miss;

    if (is_ship_sunk) {
        onShipSunk();
        return;
    }

    if (is_hit) {
        onHit(position);
    }
}

void BotSonnet::onHit(const Board::Position& pos) {
    mode_ = Mode::Target;
    current_hit_chain_.push_back(pos);
    enqueueNeighbors(pos);
}

void BotSonnet::onShipSunk() {
    // Determine sunk ship size
    size_t sunk_size = current_hit_chain_.size();

    // Find and remove the matching ship size from remaining ships
    auto it = std::find(remaining_ship_sizes_.begin(),
                        remaining_ship_sizes_.end(),
                        sunk_size);

    if (it != remaining_ship_sizes_.end()) {
        remaining_ship_sizes_.erase(it);
        LOG_V("Ship of size {} sunk. Ships remaining", sunk_size, remaining_ship_sizes_.size());
    } else {
        // This might happen if we hit cells from multiple ships
        // Try to find the best match
        LOG_W("Could not find exact match for sunk ship of size {}", sunk_size);

        // Find closest size >= sunk_size
        auto closest = std::find_if(remaining_ship_sizes_.begin(),
                                    remaining_ship_sizes_.end(),
                                    [sunk_size](size_t s) { return s >= sunk_size; });
        if (closest != remaining_ship_sizes_.end()) {
            remaining_ship_sizes_.erase(closest);
        }
    }

    // Mark cells around the sunk ship as effectively "miss" since ships can't be adjacent
    // (if your game rules have this constraint)
    for (const auto& hit_pos : current_hit_chain_) {
        static const int dr[] = {-1, -1, -1, 0, 0, 1, 1, 1};
        static const int dc[] = {-1, 0, 1, -1, 1, -1, 0, 1};

        for (int i = 0; i < 8; ++i) {
            int nr = hit_pos.first + dr[i];
            int nc = hit_pos.second + dc[i];

            if (nr >= 0 && nr < static_cast<int>(Board::kBoardSizeRow) &&
                nc >= 0 && nc < static_cast<int>(Board::kBoardSizeCol)) {
                // Mark diagonal and adjacent cells as "tried" if unknown
                if (cell_states_[nr][nc] == CellState::Unknown) {
                    tried_[nr][nc] = true;
                    // Don't change cell_state - keep it Unknown for probability calc
                    // But it won't be selected since tried_ is true
                }
            }
        }
    }

    // Reset targeting state
    mode_ = Mode::Hunt;
    target_queue_.clear();
    current_hit_chain_.clear();
}

void BotSonnet::enqueueNeighbors(const Board::Position& pos) {
    static const int dr[] = {-1, 1, 0, 0};
    static const int dc[] = {0, 0, -1, 1};

    for (int i = 0; i < 4; ++i) {
        Board::Position next{pos.first + dr[i], pos.second + dc[i]};

        if (isValidTarget(next)) {
            // Avoid duplicates in queue
            bool already_queued = std::find_if(target_queue_.begin(),
                target_queue_.end(),
                [&next](const Board::Position& p) {
                    return p.first == next.first && p.second == next.second;
                }) != target_queue_.end();

            if (!already_queued) {
                target_queue_.push_back(next);
            }
        }
    }
}

