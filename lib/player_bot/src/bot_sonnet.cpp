Board::Position BotSonnet::randomPosition() const {
    std::uniform_int_distribution<int> row(0, static_cast<int>(Board::kBoardSizeRow) - 1);
    std::uniform_int_distribution<int> col(0, static_cast<int>(Board::kBoardSizeCol) - 1);
    return {row(gen_), col(gen_)};
}

bool BotSonnet::isValidTarget(const Board::Position& pos) const {
    if (pos.first < 0 || pos.second < 0) return false;
    if (static_cast<size_t>(pos.first) >= Board::kBoardSizeRow ||
        static_cast<size_t>(pos.second) >= Board::kBoardSizeCol)
        return false;
    return !tried_[pos.first][pos.second] &&
           Board::Board::is_valid_shot(oponent_board_, pos);
}
