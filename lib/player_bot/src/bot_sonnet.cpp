void BotSonnet::prioritizeTargetQueue() {
    if (target_queue_.size() <= 1) return;

    // Remove invalid targets first
    target_queue_.erase(
        std::remove_if(target_queue_.begin(), target_queue_.end(),
            [this](const Board::Position& p) { return !isValidTarget(p); }),
        target_queue_.end());

    if (target_queue_.size() <= 1) return;

    // If we have 2+ hits, we know the ship's orientation
    auto [is_horizontal, is_vertical] = detectHitOrientation();

    if (is_horizontal || is_vertical) {
        filterTargetQueueByOrientation();
    }

    // Sort remaining targets by likelihood
    std::sort(target_queue_.begin(), target_queue_.end(),
        [this](const Board::Position& a, const Board::Position& b) {
            // Prefer cells that extend the hit chain at endpoints
            if (current_hit_chain_.empty()) return false;

            auto [is_horiz, is_vert] = detectHitOrientation();

            auto get_endpoint_priority = [&](const Board::Position& pos) -> int {
                if (current_hit_chain_.size() < 2) {
                    // Just count adjacency to any hit
                    int adj_count = 0;
                    for (const auto& hit : current_hit_chain_) {
                        if (std::abs(pos.first - hit.first) +
                            std::abs(pos.second - hit.second) == 1) {
                            adj_count++;
                        }
                    }
                    return adj_count;
                }

                // Find endpoints of the chain
                auto [min_row_it, max_row_it] = std::minmax_element(
                    current_hit_chain_.begin(), current_hit_chain_.end(),
                    [](const auto& p1, const auto& p2) { return p1.first < p2.first; });
                auto [min_col_it, max_col_it] = std::minmax_element(
                    current_hit_chain_.begin(), current_hit_chain_.end(),
                    [](const auto& p1, const auto& p2) { return p1.second < p2.second; });

                // Check if pos extends from an endpoint
                if (is_horiz) {
                    if (pos.first == min_col_it->first) {
                        if (pos.second == min_col_it->second - 1 ||
                            pos.second == max_col_it->second + 1) {
                            return 10;  // High priority - extends the line
                        }
                    }
                } else if (is_vert) {
                    if (pos.second == min_row_it->second) {
                        if (pos.first == min_row_it->first - 1 ||
                            pos.first == max_row_it->first + 1) {
                            return 10;  // High priority - extends the line
                        }
                    }
                }
                return 0;
            };

            return get_endpoint_priority(a) > get_endpoint_priority(b);
        });
}

std::pair<bool, bool> BotSonnet::detectHitOrientation() const {
    if (current_hit_chain_.size() < 2) {
        return {false, false};
    }

    bool same_row = true;
    bool same_col = true;

    for (size_t i = 1; i < current_hit_chain_.size(); ++i) {
        if (current_hit_chain_[i].first != current_hit_chain_[0].first) {
            same_row = false;
        }
        if (current_hit_chain_[i].second != current_hit_chain_[0].second) {
            same_col = false;
        }
    }

    return {same_row, same_col};  // {horizontal, vertical}
}

void BotSonnet::filterTargetQueueByOrientation() {
    auto [is_horizontal, is_vertical] = detectHitOrientation();

    if (!is_horizontal && !is_vertical) return;
    if (current_hit_chain_.empty()) return;

    // Find the extent of current hit chain
    auto [min_row_it, max_row_it] = std::minmax_element(
        current_hit_chain_.begin(), current_hit_chain_.end(),
        [](const auto& p1, const auto& p2) { return p1.first < p2.first; });
    auto [min_col_it, max_col_it] = std::minmax_element(
        current_hit_chain_.begin(), current_hit_chain_.end(),
        [](const auto& p1, const auto& p2) { return p1.second < p2.second; });

    std::deque<Board::Position> filtered;

    for (const auto& target : target_queue_) {
        bool keep = false;

        if (is_horizontal) {
            // Ship is horizontal - only keep targets in the same row
            if (target.first == current_hit_chain_[0].first) {
                // Check if it's at an endpoint
                if (target.second == min_col_it->second - 1 ||
                    target.second == max_col_it->second + 1) {
                    keep = true;
                }
            }
        }

        if (is_vertical) {
            // Ship is vertical - only keep targets in the same column
            if (target.second == current_hit_chain_[0].second) {
                // Check if it's at an endpoint
                if (target.first == min_row_it->first - 1 ||
                    target.first == max_row_it->first + 1) {
                    keep = true;
                }
            }
        }

        if (keep) {
            filtered.push_back(target);
        }
    }

    // Only apply filter if we still have targets
    if (!filtered.empty()) {
        target_queue_ = std::move(filtered);
    }
}

